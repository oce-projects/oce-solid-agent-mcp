# repo-map.ps1 - writes the mechanical part of REPO-MAP.md, and checks that the map is not stale.
#
# Version 1.0.0
# Changelog:
#   1.0.0 (08/11/2026) first version. The tree, the counts and the lists are produced here, never by
#         hand; the words come from Ops\repo-map.folders.psd1; the rest of REPO-MAP.md (where to find
#         what, the flows) is written by hand OUTSIDE the generated block.
#
# What -Check fails on (exit 1), each line says which:
#   - a top-level folder or a root file of the repository without a description in the data file;
#   - a description for a folder or a file that no longer exists;
#   - a folder or file in the generated block that does not exist, or one that exists and is missing
#     from the block (a new sub-folder of an expanded folder, for instance): run -Write;
#   - a path cited anywhere in REPO-MAP.md (in `code` or in a link) that does not exist and is not
#     under one of the GeneratedRoots of the data file. Words with a slash that are not paths (MCP
#     method names such as tools/call) are listed in NotPaths of the data file.
# Counts are NOT compared: a new case file must not make the map stale; a new folder must.
#
# "The repository" is what git tracks plus the new files git does not ignore (so that a file not yet
# committed is mapped), minus the Skip folders of the data file.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File Ops\commands\repo-map.ps1 -Write [-Root <repo>]
#   powershell -NoProfile -ExecutionPolicy Bypass -File Ops\commands\repo-map.ps1 -Check [-Root <repo>]
#
# Exit codes: 0 written, or up to date; 1 stale (with -Check); 2 usage error (no markers, no data file).
param([switch] $Write, [switch] $Check, [string] $Root = '')
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot) }
$Root = (Resolve-Path -LiteralPath $Root).Path
$mapFile = Join-Path $Root 'REPO-MAP.md'
$dataFile = Join-Path $Root 'Ops\repo-map.folders.psd1'
$begin = '<!-- GENERATED BY Ops/commands/repo-map.ps1: BEGIN (do not edit by hand) -->'
$end = '<!-- GENERATED BY Ops/commands/repo-map.ps1: END -->'
function Stop-Map([int]$c, [string]$m) { [Console]::Out.WriteLine("STOP (exit $c): $m"); exit $c }
if (-not ($Write -xor $Check)) { Stop-Map 2 'say -Write or -Check' }
if (-not (Test-Path -LiteralPath $dataFile)) { Stop-Map 2 "no data file: $dataFile" }
if (-not (Test-Path -LiteralPath $mapFile)) { Stop-Map 2 "no map: $mapFile" }
$data = Import-PowerShellDataFile -LiteralPath $dataFile

$old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
$files = @(& git.exe -C $Root ls-files 2>$null) + @(& git.exe -C $Root ls-files --others --exclude-standard 2>$null)
$ErrorActionPreference = $old
$files = @($files | Where-Object { $_ } | ForEach-Object { $_ -replace '\\', '/' } | Sort-Object -Unique |
    Where-Object { $f = $_; -not (@($data.Skip) | Where-Object { $f -eq $_ -or $f.StartsWith($_ + '/') }) } |
    Where-Object { Test-Path -LiteralPath (Join-Path $Root $_) -PathType Leaf })
if ($files.Count -eq 0) { Stop-Map 2 "git lists no file in $Root" }
$tops = @($files | Where-Object { $_ -match '/' } | ForEach-Object { ($_ -split '/')[0] } | Sort-Object -Unique)
$rootFiles = @($files | Where-Object { $_ -notmatch '/' } | Sort-Object)
function Count-Under([string]$dir) { @($files | Where-Object { $_.StartsWith($dir + '/') }).Count }
function Sub-Folders([string]$dir) {
    $n = ($dir -split '/').Count
    @($files | Where-Object { $_.StartsWith($dir + '/') } | ForEach-Object { $s = $_ -split '/'; if ($s.Count -gt $n + 1) { $s[$n] } } | Sort-Object -Unique)
}
function Cell([string]$t) { ($t -replace '\|', '/') }

# ---- the generated block -------------------------------------------------------------
$g = New-Object System.Collections.Generic.List[string]
$g.Add($begin)
$g.Add('')
$g.Add("Files in the map: $($files.Count) (tracked, plus new files git does not ignore). Counts are those of the last -Write.")
$g.Add('')
$g.Add('### Folders')
$g.Add('')
$g.Add('| folder | files | what it is | read by | written by |')
$g.Add('|---|---|---|---|---|')
foreach ($t in $tops) {
    $d = $data.Folders[$t]
    if ($d) { $g.Add(('| `{0}/` | {1} | {2} | {3} | {4} |' -f $t, (Count-Under $t), (Cell $d.What), (Cell $d.ReadBy), (Cell $d.WrittenBy))) }
    else { $g.Add(('| `{0}/` | {1} | (no description) | | |' -f $t, (Count-Under $t))) }
}
$g.Add('')
$g.Add('### Sub-folders')
$g.Add('')
foreach ($e in @($data.Expand)) {
    $subs = @(Sub-Folders $e)
    if ($subs.Count -eq 0) { continue }
    $g.Add(('- `{0}/`: {1}' -f $e, (($subs | ForEach-Object { '`' + $_ + '/` (' + (Count-Under "$e/$_") + ')' }) -join ', ')))
}
$g.Add('')
$g.Add('### Root files')
$g.Add('')
$g.Add('| file | what it is | read by | written by |')
$g.Add('|---|---|---|---|')
foreach ($r in $rootFiles) {
    $d = $data.RootFiles[$r]
    if ($d) { $g.Add(('| `{0}` | {1} | {2} | {3} |' -f $r, (Cell $d.What), (Cell $d.ReadBy), (Cell $d.WrittenBy))) }
    else { $g.Add(('| `{0}` | (no description) | | |' -f $r)) }
}
$g.Add('')
$g.Add('### Files by extension')
$g.Add('')
$byExt = $files | Group-Object { $x = [IO.Path]::GetExtension($_).ToLower(); if ($x) { $x } else { '(none)' } } | Sort-Object Count -Descending
$g.Add((($byExt | Select-Object -First 12 | ForEach-Object { '`' + $_.Name + '` ' + $_.Count }) -join ', '))
$g.Add('')
$g.Add($end)

$text = [IO.File]::ReadAllText($mapFile)
$i = $text.IndexOf($begin); $j = $text.IndexOf($end)
if ($i -lt 0 -or $j -lt $i) { Stop-Map 2 "REPO-MAP.md has no generated block (markers '$begin' ... '$end')" }

if ($Write) {
    $new = $text.Substring(0, $i) + ($g -join "`n") + $text.Substring($j + $end.Length)
    [IO.File]::WriteAllText($mapFile, $new, (New-Object System.Text.UTF8Encoding $false))
    [Console]::Out.WriteLine("written: $mapFile ($($tops.Count) folders, $($rootFiles.Count) root files, $($files.Count) files)")
}

# ---- the check (also after -Write, so that -Write says what is still missing) ------
$text = [IO.File]::ReadAllText($mapFile)
$i = $text.IndexOf($begin); $j = $text.IndexOf($end)
$block = $text.Substring($i, $j - $i)
$problems = New-Object System.Collections.Generic.List[string]
foreach ($t in $tops) { if (-not $data.Folders.ContainsKey($t)) { $problems.Add("folder without a description in Ops/repo-map.folders.psd1: $t/") } }
foreach ($k in $data.Folders.Keys) { if ($tops -notcontains $k) { $problems.Add("description of a folder that does not exist: $k/") } }
foreach ($r in $rootFiles) { if (-not $data.RootFiles.ContainsKey($r)) { $problems.Add("root file without a description in Ops/repo-map.folders.psd1: $r") } }
foreach ($k in $data.RootFiles.Keys) { if ($rootFiles -notcontains $k) { $problems.Add("description of a root file that does not exist: $k") } }
foreach ($e in @($data.Expand)) { if ((Count-Under $e) -eq 0) { $problems.Add("Expand names a folder that does not exist: $e") } }
# what the block says against what exists
foreach ($t in $tops) { if ($block -notmatch [regex]::Escape('| `' + $t + '/` |')) { $problems.Add("folder missing from the generated block: $t/ (run -Write)") } }
foreach ($r in $rootFiles) { if ($block -notmatch [regex]::Escape('| `' + $r + '` |')) { $problems.Add("root file missing from the generated block: $r (run -Write)") } }
foreach ($e in @($data.Expand)) {
    foreach ($s in @(Sub-Folders $e)) { if ($block -notmatch [regex]::Escape('`' + $s + '/` (')) { $problems.Add("sub-folder missing from the generated block: $e/$s/ (run -Write)") } }
}
foreach ($m in [regex]::Matches($block, '\| `([^`]+)/` \|')) { if ($tops -notcontains $m.Groups[1].Value) { $problems.Add("the generated block names a folder that does not exist: $($m.Groups[1].Value)/ (run -Write)") } }
foreach ($m in [regex]::Matches($block, '^- `([^`]+)/`: (.*)$', 'Multiline')) {
    $e = $m.Groups[1].Value
    foreach ($s in [regex]::Matches($m.Groups[2].Value, '`([^`]+)/` \(')) { if ((Count-Under "$e/$($s.Groups[1].Value)") -eq 0) { $problems.Add("the generated block names a sub-folder that does not exist: $e/$($s.Groups[1].Value)/ (run -Write)") } }
}
foreach ($m in [regex]::Matches($block, '^\| `([^`/]+)` \|', 'Multiline')) { if ($rootFiles -notcontains $m.Groups[1].Value) { $problems.Add("the generated block names a root file that does not exist: $($m.Groups[1].Value) (run -Write)") } }

# every path cited in the map exists
$leaves = @{}; foreach ($f in $files) { $leaves[(Split-Path $f -Leaf).ToLower()] = $true }
$dirs = @{}; foreach ($f in $files) { $p = $f; while ($p -match '/') { $p = $p.Substring(0, $p.LastIndexOf('/')); $dirs[$p.ToLower()] = $true } }
$fileSet = @{}; foreach ($f in $files) { $fileSet[$f.ToLower()] = $true }
$exts = '\.(md|ps1|psd1|cs|csproj|json|js|txt|yml|tsv|html|cjs|sh)$'
$cited = New-Object System.Collections.Generic.List[string]
foreach ($m in [regex]::Matches($text, '`([^`\r\n]+)`')) { $cited.Add($m.Groups[1].Value) }
foreach ($m in [regex]::Matches($text, '\]\(([^)\s#]+)(#[^)]*)?\)')) { if ($m.Groups[1].Value -notmatch '^[a-z]+://') { $cited.Add($m.Groups[1].Value) } }
$checked = 0
foreach ($c in ($cited | Sort-Object -Unique)) {
    if ($c -match '[\s<>*{}$%|=:"]' -or $c -match '^-') { continue }
    $p = ($c -replace '\\', '/').TrimEnd('/')
    while ($p.StartsWith('./')) { $p = $p.Substring(2) }   # never TrimStart('.'): it eats the dot of .github
    if (@($data.NotPaths) -contains $p) { continue }
    if (-not $p) { continue }
    $hasSep = $p -match '/'
    if (-not $hasSep -and $p -notmatch $exts) { continue }
    $checked++
    $low = $p.ToLower()
    if (-not $hasSep) {
        if ($leaves.ContainsKey($low)) { continue }
        if ($p -match '^\.[A-Za-z0-9]+$') { $checked--; continue }   # an extension (`.cs`), not a file
        $problems.Add("cited file not in the repository: $c"); continue
    }
    if ($fileSet.ContainsKey($low) -or $dirs.ContainsKey($low)) { continue }
    $gen = @(@($data.GeneratedRoots) | Where-Object { $low -like ($_.ToLower()) -or $low -like ($_.ToLower() + '/*') }).Count -gt 0
    if (-not $gen) { $problems.Add("cited path does not exist: $c") }
}
[Console]::Out.WriteLine("checked: $($tops.Count) folders, $($rootFiles.Count) root files, $checked cited paths")
foreach ($p in $problems) { [Console]::Out.WriteLine("STALE $p") }
if ($problems.Count -gt 0) { [Console]::Out.WriteLine("the map is stale: $($problems.Count) problems"); exit 1 }
[Console]::Out.WriteLine('the map is up to date')
exit 0
